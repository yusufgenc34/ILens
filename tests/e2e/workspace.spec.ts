test('the hex editor shows the whole file and checks raw byte patches', async ({page}, testInfo) => {
  await page.goto('./'); await expect(page.getByLabel('Open assembly files')).toBeEnabled()
  await page.getByLabel('Open assembly files').setInputFiles(path.resolve('samples/fixtures/ILens.Dependency.dll'))
  await expect(page.getByRole('main')).toHaveAttribute('data-assembly-id', '1')
  await page.getByRole('treeitem', {name: /^ILens\.Dependency$/}).first().click()
  await page.getByRole('tab', {name: 'Hex', exact: true}).click()
  const hex = page.getByRole('region', {name: 'Hex editor'})
  await expect(hex.getByLabel('Byte 0x00000000')).toHaveText('4D')
  await expect(hex.getByLabel('Byte 0x00000001')).toHaveText('5A')
  await hex.getByLabel('Go to offset').fill('80'); await hex.getByRole('button', {name: 'Go', exact: true}).click()
  await expect(hex.getByLabel('Byte 0x00000080')).toHaveText('50')
  await hex.getByRole('button', {name: 'Edit bytes'}).click()
  // An unused DOS header byte keeps the file valid; the MZ signature does not.
  await hex.getByLabel('Go to offset').fill('2'); await hex.getByRole('button', {name: 'Go', exact: true}).click()
  await hex.getByLabel('File bytes').focus(); await page.keyboard.type('ff')
  await expect(hex.getByLabel('Byte 0x00000002')).toHaveText('FF')
  await hex.getByRole('button', {name: 'Check'}).click()
  await expect(hex).toContainText('still parses as a managed assembly')
  await hex.getByLabel('Byte 0x00000000').click(); await hex.getByLabel('File bytes').focus(); await page.keyboard.type('00')
  await hex.getByRole('button', {name: 'Check'}).click()
  await expect(hex).toContainText('no longer parses')
  await page.screenshot({path: testInfo.outputPath('hex-editor.png'), animations: 'disabled'})
  const download = page.waitForEvent('download'); await hex.getByRole('button', {name: 'Download patched file'}).click()
  const file = await fs.readFile((await (await download).path())!)
  expect(file[0]).toBe(0); expect(file[2]).toBe(0xff)
})
