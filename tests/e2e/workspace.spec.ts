test('local enum edits produce an independently verified DLL', async ({page},info) => {
  test.setTimeout(90_000)
  await open(page)
  for (const name of ['ChooseMode','ReadMode','StoreMode','BoxMode','UnboxMode','ReadLongMode','StoreLongMode']) {
    await find(page,name)
    await page.getByRole('tab',{name:'IL',exact:true}).click()
    await page.getByRole('button',{name:'Edit IL',exact:true}).click()
    const dialog = page.getByRole('dialog',{name:'Edit method IL',exact:true})
    await dialog.getByLabel('Insert before IL_0000',{exact:true}).click()
    await dialog.getByRole('button',{name:'Validate and apply',exact:true}).click()
    await expect(dialog).toContainText('Validation passed.')
    await dialog.getByRole('button',{name:'Close IL editor'}).click()
  }
  await page.getByRole('menuitem',{name:'File',exact:true}).click()
  await page.getByRole('menuitem',{name:'Save Module…',exact:true}).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button',{name:'Download modified assembly'}).click()
  const file = info.outputPath('ILens.Workspace.modified.dll'); await (await download).saveAs(file)
  const runtimes = execFileSync('dotnet',['--list-runtimes'],{encoding:'utf8'})
  const runtime = runtimes.split('\n').find(line => line.startsWith('Microsoft.NETCore.App 10.'))!.match(/^Microsoft.NETCore.App (\S+) \[(.+)\]$/)!
  const verified = execFileSync('dotnet',['tool','run','ilverify',file,'-r',path.join(runtime[2],runtime[1],'*.dll'),'-r',path.resolve('samples/fixtures/ILens.WorkspaceDependency.dll'),'-s','System.Private.CoreLib'],{encoding:'utf8',timeout:30_000})
  expect(verified).toContain('Verified')
  await page.getByRole('button',{name:'Close export'}).click()
  await page.getByRole('button',{name:'Close workspace',exact:true}).click()
  await page.getByLabel('Open assembly files').setInputFiles(file)
  await expect(page.getByRole('main')).toHaveAttribute('data-assembly-id','1')
  await find(page,'ChooseMode'); await page.getByRole('tab',{name:'IL',exact:true}).click()
  await expect(page.getByLabel('IL code viewer')).toContainText('nop')
})
