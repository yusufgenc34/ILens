  await expect(page.getByRole('main')).toHaveAttribute('data-assembly-id','1')
  await expect(viewer).toContainText('widget.Text = value')
  await expect(page.getByRole('tablist',{name:'Open documents'}).getByRole('tab')).toHaveCount(3)
